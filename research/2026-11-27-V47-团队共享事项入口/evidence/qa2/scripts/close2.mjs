const ts = () => new Date().toISOString();
const T = (s) => s.replace(/\s+/g, " ");
export default async ({ page, shot }) => {
  page.on("response", async (r) => { if (!r.url().includes("/invoke")) return; try { const b = JSON.parse(r.request().postData() || "{}"); if (/^(policy|firm_policy)/.test(b.method) && !/status|drafts|^policy\.get/.test(b.method)) console.log(ts(), "INVOKE", b.method, "→", (await r.text()).slice(0, 400)); } catch {} });
  await page.waitForTimeout(3000);
  const base = page.url().split("#")[0];
  await page.goto(base + "#/connections/team"); await page.waitForTimeout(4500);
  const row = page.locator("#row-share-relay");
  await row.locator("button", { hasText: /关闭/ }).first().click(); await page.waitForTimeout(1000);
  await page.locator(".modal, [role=dialog]").last().locator("button", { hasText: "去起草规则" }).click(); await page.waitForTimeout(2000);
  const form = page.locator(".device-row", { hasText: "起草律所策略" }).last();
  await form.scrollIntoViewIfNeeded();
  console.log("FORM relay part:", T(await form.innerText()).match(/同事之间同步.{0,160}/)?.[0]);
  await shot("4-a-close-draft-form");
  await form.locator("button", { hasText: "生成草稿" }).click(); await page.waitForTimeout(3500);
  const panel = page.locator(".panel", { hasText: "律所策略第" }).first(); await panel.scrollIntoViewIfNeeded();
  console.log("DRAFT:", T(await panel.innerText()).slice(0, 700));
  await panel.locator("button", { hasText: "核对无误，确认" }).click(); await page.waitForTimeout(3000);
  await panel.locator("button", { hasText: /^\s*发布\s*$/ }).click(); await page.waitForTimeout(600);
  await page.locator("button:visible", { hasText: "确定发布" }).click(); console.log(ts(), "PUBLISHED click"); await page.waitForTimeout(4000);
  await row.scrollIntoViewIfNeeded();
  console.log("ROW AFTER CLOSE:", T(await row.innerText()));
  await shot("4-a-closed-row");
  if (!process.env.REOPEN) return;
  await row.locator("button", { hasText: /重新开通/ }).first().click(); await page.waitForTimeout(1500);
  const m = page.locator(".modal, [role=dialog]").last();
  console.log("REOPEN MODAL:", T(await m.innerText()).slice(0, 1500));
  await shot("4-a-reopen-modal");
  await m.locator("button.btn-primary").last().click(); console.log(ts(), "REOPEN GO"); await page.waitForTimeout(5000);
  console.log("TOAST:", T((await page.locator("[role=status], .toast").allInnerTexts()).join(" | ")).slice(0, 400));
  console.log("ROW AFTER REOPEN:", T(await row.innerText()));
  await row.scrollIntoViewIfNeeded(); await shot("4-a-reopened-row");
};
