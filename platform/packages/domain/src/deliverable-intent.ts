/**
 * 律师要的交付物是不是 Word 文书（V12）：纯函数、无依赖，界面（首页建议卡片）与内核（自由描述任务的主交付物核对）共用同一口径。
 * 以子路径 @zr-legal/domain/deliverable-intent 导出，渲染进程可直接引用（不带入 node:crypto 等）。
 */

/** 让“回稿”类排除词失效的我方修订说法（V12）：要修订稿、清洁稿，在原件上改，按……意见改，直接修改对方回稿。 */
export const OWN_REVISION_RE = /修订稿|清洁稿|清洁版|修订版|原件上|直接改|直接修改|按[^，。；]{0,12}意见(?:直接|逐条|逐处)?(?:修改|修订|改)(?!了)|(?:修改|修订)(?:一下)?(?:这份|对方的?)?回稿/;

/**
 * 律师要的成果是 Word 文书（V12）：起草、修改一类动作的对象是文书（合同、协议、……状、……书、……函、报告、意见书、决议……），
 * 且同一短语里没有点名表格（清单、表、目录、矩阵、时间线、Excel），或者点名要我方修订稿、清洁稿。
 * 起草依据里的“违约金计算”“诉讼时效”“交割清单”“回稿”“核对引用”“补证”命中字数常比文书名多，原先被建议成金额测算、程序核查、
 * 交割清单、回稿比对这类只出 Excel 的卡；按建议发起后内核按卡的主交付物要求“必须用 xlsx.render_table 出表”，律师要的文书不出
 * （V12 走查：要求起草或修订法律文书，最终输出 Excel）。“起草的合同”“修改后的合同”“修改意见 / 修改建议”是材料或审查成果，不算。
 */
const DOC_OBJECT_RE = /(?:起草|草拟|撰写|拟写|拟定|出具|修改|修订|(?:写|拟|出|做)(?:一份|一个|一封|一套|份|个|封))(?:一份|一个|一封|一套|份|个|封)?(?![的了过]|后的|好的|完的|建议|意见(?!书))([^，。；;！？!?,、\n]{1,40})/g;
const DOC_NOUN_RE = /合同|协议|章程|起诉状|答辩状|上诉状|诉状|申请书|答辩书|意见书|法律意见|质证意见|代理意见|代理词|律师函|催告函|催款函|函件|确认函|豁免函|告知函|通知|决议|决定书|报告|备忘录|纪要|提纲|说明|文书/;
const SHEET_NOUN_RE = /清单|(?<!代|发)表(?!决|述|示|明)|目录|台账|矩阵|时间[线轴]|明细|excel/i;
export function wantsWordDocument(text: string): boolean {
  if (OWN_REVISION_RE.test(text)) return true;
  for (const m of text.matchAll(DOC_OBJECT_RE)) {
    const obj = m[1]!;
    if (DOC_NOUN_RE.test(obj) && !SHEET_NOUN_RE.test(obj)) return true;
  }
  return false;
}
